// ignore_for_file: avoid_print
/// Generates concrete, serializable AST implementations from abstract classes.
///
/// This script reads the abstract AST classes from ast_model.dart and generates:
/// 1. Concrete implementations with backing fields
/// 2. JSON serialization/deserialization support
/// 3. Factory constructors for creating instances
import 'dart:io';

import 'package:path/path.dart' as p;

void main() async {
  final projectRoot = p.dirname(p.dirname(Platform.script.toFilePath()));
  final abstractPath =
      p.join(projectRoot, 'lib', 'src', 'analyzer', 'ast_model.dart');
  final outputPath =
      p.join(projectRoot, 'lib', 'src', 'serializable', 'ast_nodes.dart');
  final converterPath =
      p.join(projectRoot, 'lib', 'src', 'serializable', 'ast_converter.dart');

  print('Reading abstract classes from: $abstractPath');

  final abstractContent = File(abstractPath).readAsStringSync();
  final generator = SerializableAstGenerator(abstractContent);

  // Generate the serializable implementations
  final nodesContent = generator.generateNodes();
  final converterContent = generator.generateConverter();

  // Ensure output directory exists
  Directory(p.dirname(outputPath)).createSync(recursive: true);

  // Write generated files
  File(outputPath).writeAsStringSync(nodesContent);
  print('Generated: ${p.basename(outputPath)} (${generator.classCount} classes)');

  File(converterPath).writeAsStringSync(converterContent);
  print('Generated: ${p.basename(converterPath)}');

  print('\nDone!');
}

/// Parses abstract classes and generates concrete implementations.
class SerializableAstGenerator {
  final String sourceContent;
  final List<ClassInfo> _classes = [];

  int get classCount => _classes.length;

  SerializableAstGenerator(this.sourceContent) {
    _parseClasses();
  }

  void _parseClasses() {
    // Simple regex-based parser for abstract class definitions
    final classPattern = RegExp(
      r'^abstract class (\w+)(?:<([^>]+)>)?(?:\s+extends\s+(\w+))?(?:\s+implements\s+([^{]+))?\s*\{',
      multiLine: true,
    );

    final memberPattern = RegExp(
      r'^\s+(\w+(?:<[^>]+>)?(?:\?)?)\s+get\s+(\w+);',
      multiLine: true,
    );

    final methodPattern = RegExp(
      r'^\s+(\w+(?:<[^>]+>)?(?:\?)?)\s+(\w+)\s*(?:<([^>]+)>)?\s*\(([^)]*)\);',
      multiLine: true,
    );

    // Find all class definitions
    final classMatches = classPattern.allMatches(sourceContent);

    for (final match in classMatches) {
      final className = match.group(1)!;
      final typeParams = match.group(2);
      final extendsClass = match.group(3);
      final implementsClause = match.group(4);

      // Skip *Impl classes - they're internal
      if (className.endsWith('Impl')) continue;

      // Find the class body
      final startIndex = match.end;
      final endIndex = _findMatchingBrace(sourceContent, startIndex - 1);
      if (endIndex == -1) continue;

      final classBody = sourceContent.substring(startIndex, endIndex);

      // Parse getters (properties)
      final properties = <PropertyInfo>[];
      for (final propMatch in memberPattern.allMatches(classBody)) {
        properties.add(PropertyInfo(
          type: propMatch.group(1)!,
          name: propMatch.group(2)!,
        ));
      }

      // Parse methods
      final methods = <MethodInfo>[];
      for (final methodMatch in methodPattern.allMatches(classBody)) {
        methods.add(MethodInfo(
          returnType: methodMatch.group(1)!,
          name: methodMatch.group(2)!,
          typeParams: methodMatch.group(3),
          params: methodMatch.group(4)!,
        ));
      }

      final interfaces = implementsClause
              ?.split(',')
              .map((s) => s.trim())
              .where((s) => s.isNotEmpty)
              .toList() ??
          [];

      _classes.add(ClassInfo(
        name: className,
        typeParams: typeParams,
        extendsClass: extendsClass,
        interfaces: interfaces,
        properties: properties,
        methods: methods,
      ));
    }
  }

  int _findMatchingBrace(String source, int openBraceIndex) {
    var depth = 1;
    for (var i = openBraceIndex + 1; i < source.length; i++) {
      if (source[i] == '{') depth++;
      if (source[i] == '}') depth--;
      if (depth == 0) return i;
    }
    return -1;
  }

  String generateNodes() {
    final buffer = StringBuffer();

    buffer.writeln('// Generated serializable AST node implementations');
    buffer.writeln('// DO NOT EDIT - Generated by generate_serializable_ast.dart');
    buffer.writeln('// ignore_for_file: unused_element, unused_field');
    buffer.writeln(
        '// ignore_for_file: annotate_overrides, constant_identifier_names');
    buffer.writeln('// ignore_for_file: prefer_initializing_formals');
    buffer.writeln();
    buffer.writeln("import 'dart:convert';");
    buffer.writeln();
    buffer.writeln("import '../analyzer/_stub_types.dart';");
    buffer.writeln("import '../analyzer/ast_model.dart';");
    buffer.writeln();

    // Generate SerializableToken first
    buffer.writeln(_generateSerializableToken());
    buffer.writeln();

    // Generate base serialization mixin
    buffer.writeln(_generateSerializationMixin());
    buffer.writeln();

    // Generate concrete classes
    for (final cls in _classes) {
      // Skip non-AST classes (Element, Type, etc.)
      if (!_isAstClass(cls)) continue;

      buffer.writeln(_generateConcreteClass(cls));
      buffer.writeln();
    }

    return buffer.toString();
  }

  bool _isAstClass(ClassInfo cls) {
    // Only generate for AST node classes
    final astInterfaces = [
      'AstNode',
      'SyntacticEntity',
      'Expression',
      'Statement',
      'Declaration',
      'Directive',
      'TypeAnnotation',
      'FormalParameter',
      'CollectionElement',
      'DartPattern',
      'StringLiteral',
      'Literal',
      'Identifier',
      'FunctionBody',
      'Combinator',
      'Configuration',
      'ConstructorInitializer',
      'CatchClause',
      'Assertion',
      'Comment',
      'CompilationUnit',
      'ArgumentList',
      'TypeArgumentList',
      'TypeParameterList',
      'FormalParameterList',
      'AnnotatedNode',
    ];

    if (cls.interfaces.any((i) => astInterfaces.contains(i))) return true;
    if (astInterfaces.contains(cls.name)) return true;
    if (cls.extendsClass != null &&
        astInterfaces.contains(cls.extendsClass)) return true;

    return false;
  }

  String _generateSerializableToken() {
    return '''
/// Serializable token representation
class SerializableToken extends Token {
  final int _offset;
  final int _length;
  final String _lexeme;
  final String _type;

  SerializableToken({
    required int offset,
    required int length,
    required String lexeme,
    String type = 'unknown',
  })  : _offset = offset,
        _length = length,
        _lexeme = lexeme,
        _type = type;

  @override
  int get offset => _offset;
  
  @override
  int get length => _length;
  
  @override
  String get lexeme => _lexeme;
  
  String get type => _type;

  Map<String, dynamic> toJson() => {
        'offset': _offset,
        'length': _length,
        'lexeme': _lexeme,
        'type': _type,
      };

  factory SerializableToken.fromJson(Map<String, dynamic> json) {
    return SerializableToken(
      offset: json['offset'] as int,
      length: json['length'] as int,
      lexeme: json['lexeme'] as String,
      type: json['type'] as String? ?? 'unknown',
    );
  }
}''';
  }

  String _generateSerializationMixin() {
    return '''
/// Mixin providing JSON serialization for AST nodes
mixin SerializableAstNode {
  /// The node type identifier for deserialization
  String get nodeType;
  
  /// Convert this node to a JSON-serializable map
  Map<String, dynamic> toJson();
  
  /// Serialize this node to a JSON string
  String toJsonString({bool pretty = false}) {
    final encoder = pretty 
        ? const JsonEncoder.withIndent('  ')
        : const JsonEncoder();
    return encoder.convert(toJson());
  }
}

/// Factory for deserializing AST nodes from JSON
class AstNodeFactory {
  static final Map<String, SerializableAstNode Function(Map<String, dynamic>)> _factories = {};
  
  static void register(String nodeType, SerializableAstNode Function(Map<String, dynamic>) factory) {
    _factories[nodeType] = factory;
  }
  
  static SerializableAstNode? fromJson(Map<String, dynamic> json) {
    final nodeType = json['nodeType'] as String?;
    if (nodeType == null) return null;
    final factory = _factories[nodeType];
    if (factory == null) return null;
    return factory(json);
  }
}''';
  }

  String _generateConcreteClass(ClassInfo cls) {
    final buffer = StringBuffer();

    // Class name with S prefix for Serializable
    final concreteName = 'S${cls.name}';
    final typeParamsDecl =
        cls.typeParams != null ? '<${cls.typeParams}>' : '';

    // Determine what to extend/implement
    final extendsClause = '';
    final implementsList = <String>[];
    
    // Implement the original abstract class
    implementsList.add('${cls.name}$typeParamsDecl');
    implementsList.add('SerializableAstNode');

    buffer.writeln('/// Serializable implementation of [${cls.name}]');
    buffer.write('class $concreteName$typeParamsDecl $extendsClause');
    if (implementsList.isNotEmpty) {
      buffer.write('implements ${implementsList.join(', ')}');
    }
    buffer.writeln(' {');

    // Generate backing fields
    for (final prop in cls.properties) {
      final fieldType = _makeNullable(prop.type);
      buffer.writeln('  final $fieldType _${prop.name};');
    }
    buffer.writeln();

    // Generate constructor
    buffer.write('  $concreteName({');
    for (var i = 0; i < cls.properties.length; i++) {
      final prop = cls.properties[i];
      final fieldType = _makeNullable(prop.type);
      buffer.write('$fieldType ${prop.name}');
      if (i < cls.properties.length - 1) buffer.write(', ');
    }
    buffer.write('})');
    if (cls.properties.isNotEmpty) {
      buffer.write(' : ');
      for (var i = 0; i < cls.properties.length; i++) {
        final prop = cls.properties[i];
        buffer.write('_${prop.name} = ${prop.name}');
        if (i < cls.properties.length - 1) buffer.write(', ');
      }
    }
    buffer.writeln(';');
    buffer.writeln();

    // Generate getters
    for (final prop in cls.properties) {
      buffer.writeln('  @override');
      buffer.writeln(
          '  ${_makeNullable(prop.type)} get ${prop.name} => _${prop.name};');
      buffer.writeln();
    }

    // Generate nodeType
    buffer.writeln('  @override');
    buffer.writeln("  String get nodeType => '${cls.name}';");
    buffer.writeln();

    // Generate toJson
    buffer.writeln('  @override');
    buffer.writeln('  Map<String, dynamic> toJson() => {');
    buffer.writeln("        'nodeType': nodeType,");
    for (final prop in cls.properties) {
      buffer.writeln("        '${prop.name}': ${_toJsonExpr(prop)},");
    }
    buffer.writeln('      };');
    buffer.writeln();

    // Generate fromJson factory
    buffer.writeln(
        '  factory $concreteName.fromJson(Map<String, dynamic> json) {');
    buffer.writeln('    return $concreteName(');
    for (final prop in cls.properties) {
      buffer.writeln(
          "      ${prop.name}: ${_fromJsonExpr(prop, "json['${prop.name}']")},");
    }
    buffer.writeln('    );');
    buffer.writeln('  }');

    // Generate stub methods
    for (final method in cls.methods) {
      buffer.writeln();
      buffer.writeln('  @override');
      final typeParams =
          method.typeParams != null ? '<${method.typeParams}>' : '';
      buffer.writeln(
          '  ${method.returnType} ${method.name}$typeParams(${method.params}) {');
      if (method.returnType == 'void') {
        buffer.writeln("    // TODO: Implement ${method.name}");
      } else if (method.returnType.endsWith('?')) {
        buffer.writeln('    return null;');
      } else {
        buffer.writeln(
            "    throw UnimplementedError('${method.name} not implemented');");
      }
      buffer.writeln('  }');
    }

    buffer.writeln('}');

    return buffer.toString();
  }

  String _makeNullable(String type) {
    if (type.endsWith('?')) return type;
    // Some types should always be nullable in our implementation
    return '$type?';
  }

  String _toJsonExpr(PropertyInfo prop) {
    final name = '_${prop.name}';
    final type = prop.type;

    if (type.startsWith('List') || type.startsWith('NodeList')) {
      return '$name?.map((e) => _serializeNode(e)).toList()';
    }
    if (type == 'Token' || type == 'Token?') {
      return '$name is SerializableToken ? ($name as SerializableToken).toJson() : null';
    }
    if (_isPrimitiveType(type)) {
      return name;
    }
    // Assume it's an AST node
    return '_serializeNode($name)';
  }

  String _fromJsonExpr(PropertyInfo prop, String jsonExpr) {
    final type = prop.type;

    if (type.startsWith('List') || type.startsWith('NodeList')) {
      return '($jsonExpr as List?)?.cast<Map<String, dynamic>>().map((e) => AstNodeFactory.fromJson(e)).whereType<dynamic>().toList()';
    }
    if (type == 'Token' || type == 'Token?') {
      return '$jsonExpr != null ? SerializableToken.fromJson($jsonExpr as Map<String, dynamic>) : null';
    }
    if (type == 'int' || type == 'int?') {
      return '$jsonExpr as int?';
    }
    if (type == 'String' || type == 'String?') {
      return '$jsonExpr as String?';
    }
    if (type == 'bool' || type == 'bool?') {
      return '$jsonExpr as bool?';
    }
    if (type == 'double' || type == 'double?') {
      return '$jsonExpr as double?';
    }
    // Assume it's an AST node
    return '$jsonExpr != null ? AstNodeFactory.fromJson($jsonExpr as Map<String, dynamic>) : null';
  }

  bool _isPrimitiveType(String type) {
    final base = type.replaceAll('?', '');
    return ['int', 'String', 'bool', 'double', 'num'].contains(base);
  }

  String generateConverter() {
    final buffer = StringBuffer();

    buffer.writeln('// Generated AST converter from analyzer to serializable');
    buffer.writeln('// DO NOT EDIT - Generated by generate_serializable_ast.dart');
    buffer.writeln('// ignore_for_file: unused_element, unused_import');
    buffer.writeln();
    buffer.writeln("import 'package:analyzer/dart/ast/ast.dart' as analyzer;");
    buffer.writeln("import 'package:analyzer/dart/ast/visitor.dart' as analyzer;");
    buffer.writeln();
    buffer.writeln("import 'ast_nodes.dart';");
    buffer.writeln();

    buffer.writeln('''
/// Helper function to serialize any AST node
dynamic _serializeNode(dynamic node) {
  if (node == null) return null;
  if (node is SerializableAstNode) return node.toJson();
  if (node is String) return node;
  if (node is int) return node;
  if (node is double) return node;
  if (node is bool) return node;
  if (node is List) return node.map(_serializeNode).toList();
  return node.toString();
}

