    if (token == null) return null;
    return SerializableToken(
      offset: token.offset,
      length: token.length,
      lexeme: token.lexeme,
      type: token.type.toString(),
    );
  }

  List<T>? _convertNodeList<T>(analyzer.NodeList<analyzer.AstNode>? nodes) {
    if (nodes == null) return null;
