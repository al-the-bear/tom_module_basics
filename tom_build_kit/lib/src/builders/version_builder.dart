import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:build/build.dart';

/// Configuration for the version builder.
class VersionBuilderConfig {
  final String output;
  final bool includeGitCommit;

  const VersionBuilderConfig({
    this.output = 'lib/src/version.g.dart',
    this.includeGitCommit = true,
  });

  /// Load from build.yaml options.
  factory VersionBuilderConfig.fromOptions(Map<String, dynamic> options) {
    return VersionBuilderConfig(
      output: options['output'] as String? ?? 'lib/src/version.g.dart',
      includeGitCommit: options['includeGitCommit'] as bool? ?? true,
    );
  }
}

/// Build_runner builder for version file generation.
///
/// Generates a version.g.dart file with package version, build timestamp,
/// git commit hash, build number, and Dart SDK version.
class VersionBuilder implements Builder {
  final VersionBuilderConfig config;

  VersionBuilder(this.config);

  @override
  Map<String, List<String>> get buildExtensions => {
        r'$lib$': ['version.g.info'],
      };

  @override
  Future<void> build(BuildStep buildStep) async {
    final packageName = buildStep.inputId.package;

    // Read pubspec.yaml for version
    String version = '0.0.0';
    try {
      // Build step doesn't have direct file access, so we use the current dir
      final pubspecFile = File('pubspec.yaml');
      if (pubspecFile.existsSync()) {
        final content = pubspecFile.readAsStringSync();
        final match =
            RegExp(r'^version:\s*(.+)$', multiLine: true).firstMatch(content);
        if (match != null) {
          version = match.group(1)!.trim();
        }
      }
    } catch (_) {}

    // Get git commit
    String? gitCommit;
    if (config.includeGitCommit) {
      gitCommit = await _getGitCommit();
    }

    // Get build number
    final buildNumber = _getAndIncrementBuildNumber();

    // Get Dart SDK version
    final dartSdkVersion = await _getDartSdkVersion();

    // Build timestamp
    final buildTime = DateTime.now().toUtc().toIso8601String();

    // Generate content
    final content = _generateVersionFileContent(
      packageName: packageName,
      version: version,
      buildTime: buildTime,
      gitCommit: gitCommit,
      buildNumber: buildNumber,
      dartSdkVersion: dartSdkVersion,
    );

    // Write the output file
    final outputFile = File(config.output);
    outputFile.parent.createSync(recursive: true);
    outputFile.writeAsStringSync(content);

    log.info('Generated ${config.output} for $packageName v$version');
  }

  Future<String?> _getGitCommit() async {
    try {
      final result = await Process.run(
        'git',
        ['rev-parse', '--short', 'HEAD'],
      );
      if (result.exitCode == 0) {
        return result.stdout.toString().trim();
      }
    } catch (_) {}
    return null;
  }

  int _getAndIncrementBuildNumber() {
    final stateFile = File('tom_build_state.json');
    int buildNumber = 1;

    if (stateFile.existsSync()) {
      try {
        final content = stateFile.readAsStringSync();
        final json = jsonDecode(content) as Map<String, dynamic>;
        buildNumber = (json['buildNumber'] as int? ?? 0) + 1;
      } catch (_) {}
    }

    try {
      stateFile.writeAsStringSync(
        const JsonEncoder.withIndent('  ').convert({
          'buildNumber': buildNumber,
          'lastBuild': DateTime.now().toUtc().toIso8601String(),
        }),
      );
    } catch (_) {}

    return buildNumber;
  }

  Future<String?> _getDartSdkVersion() async {
    try {
      final result = await Process.run('dart', ['--version']);
      final output = result.stdout.toString() + result.stderr.toString();
      final match = RegExp(r'Dart SDK version:\s+(\S+)').firstMatch(output);
      if (match != null) return match.group(1);
      final versionMatch = RegExp(r'(\d+\.\d+\.\d+)').firstMatch(output);
      return versionMatch?.group(1);
    } catch (_) {
      return null;
    }
  }

  String _generateVersionFileContent({
    required String packageName,
    required String version,
    required String buildTime,
    String? gitCommit,
    int? buildNumber,
    String? dartSdkVersion,
  }) {
    final gitLine = gitCommit != null
        ? "  static const String gitCommit = '$gitCommit';"
        : "  static const String gitCommit = '';";
    final buildNumLine = buildNumber != null
        ? '  static const int buildNumber = $buildNumber;'
        : '  static const int buildNumber = 0;';
    final sdkLine = dartSdkVersion != null
        ? "  static const String dartSdkVersion = '$dartSdkVersion';"
        : "  static const String dartSdkVersion = '';";
    final commitSuffix = gitCommit != null ? '+$gitCommit' : '';

    return '''// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by tom_build_kit version_builder
// ignore_for_file: constant_identifier_names

/// Version information for $packageName.
class TomVersionInfo {
  TomVersionInfo._();

  static const String packageName = '$packageName';
  static const String version = '$version';
  static const String buildTime = '$buildTime';
$gitLine
$buildNumLine
$sdkLine

  /// Short version: 1.0.0
  static const String versionShort = '$version';

  /// Medium version: 1.0.0+abc1234
  static const String versionMedium = '$version$commitSuffix';

  /// Long version: 1.0.0+abc1234 (build 42, 2024-01-01T00:00:00.000Z)
  static String get versionLong =>
      '$version$commitSuffix (build \$buildNumber, \$buildTime)';
}
''';
  }
}
